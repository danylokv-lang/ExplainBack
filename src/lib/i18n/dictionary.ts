const cache = new Map<UiLocale, ReturnType<typeof build>>();

export function dictionary(locale: UiLocale) {
  let entry = cache.get(locale);
  if (!entry) {
    entry = build(locale);
    cache.set(locale, entry);
  }
  return entry;
}

export type Dictionary = ReturnType<typeof build>;
